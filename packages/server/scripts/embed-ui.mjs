// Embeds the built UI and the release version into the Worker at build time (no file reads at runtime).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
const html = readFileSync(new URL("packages/ui/dist/index.html", root), "utf8");
const { version } = JSON.parse(readFileSync(new URL("package.json", root), "utf8"));
const [major, minor] = version.split(".");

writeFileSync(
  new URL("../src/ui.generated.ts", import.meta.url),
  `// Generated by scripts/embed-ui.mjs. Do not edit.\n` +
    `export const VERSION = ${JSON.stringify(version)};\n` +
    `export const UI_URI = ${JSON.stringify(`ui://point-by-point/annotate-v${major}.${minor}.html`)};\n` +
    `export const UI_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Embedded UI (${html.length} bytes) as annotate-v${major}.${minor}.html`);
